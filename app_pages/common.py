"""Shared helpers for the Streamlit pages: styling, the synthetic-data notice and cached loading."""

import pandas as pd
import streamlit as st

from src.app_logic import (
    DATA_PATH,
    MODEL_PATH,
    REPORTS_DIR,
    load_metrics,
    load_model_or_error,
    training_ranges,
)

GITHUB_URL = "https://github.com/Ronitshah042/ai-learning"
DOCS_URL = f"{GITHUB_URL}/blob/main/docs"

CSS = """
<style>
.block-container, [data-testid="stMainBlockContainer"] { padding-top: 4.5rem; max-width: 1200px; }
.app-kicker { color: #22d3ee; font-size: 0.8rem; font-weight: 600; letter-spacing: 0.08em; text-transform: uppercase; margin-bottom: 0.25rem; }
div[data-testid="stMetric"] { background: #131c2e; border: 1px solid #1e293b; border-radius: 10px; padding: 0.75rem 1rem; }
div[data-testid="stMetricLabel"] p { color: #94a3b8; }
</style>
"""


def page_header(kicker: str, title: str, lede: str) -> None:
    """Consistent page header with a short description and the synthetic-data notice."""
    st.markdown(CSS, unsafe_allow_html=True)
    st.markdown(f'<div class="app-kicker">{kicker}</div>', unsafe_allow_html=True)
    st.title(title)
    st.markdown(f":gray[{lede}]")
    synthetic_notice()


def synthetic_notice() -> None:
    st.warning(
        "**Educational benchmark on synthetic data.** Everything here uses the synthetic UCI AI4I 2020 "
        "dataset and fields generated by this project. It is not a validated industrial system, and "
        "its outputs must not be used for real maintenance or quality decisions.",
        icon=":material/science:",
    )


@st.cache_resource(show_spinner="Loading the saved model...")
def get_model():
    """Load the saved pipeline once per server process and reuse it on every rerun."""
    return load_model_or_error(MODEL_PATH)


@st.cache_data
def get_training_ranges():
    return training_ranges(DATA_PATH)


@st.cache_data
def get_metrics():
    return load_metrics(REPORTS_DIR)


@st.cache_data
def get_feature_importance():
    path = REPORTS_DIR / "feature_importance.csv"
    return pd.read_csv(path, index_col="feature") if path.exists() else None
