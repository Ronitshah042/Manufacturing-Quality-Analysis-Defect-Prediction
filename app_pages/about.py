import streamlit as st

from app_pages.common import DOCS_URL, GITHUB_URL, page_header

page_header(
    "Project background",
    "About the Project",
    "How the data, model and evaluation fit together, and what this project can and can't show.",
)

st.subheader("Objectives")
st.markdown(
    "- Build a reproducible scikit-learn workflow that predicts machine failure from sensor readings.\n"
    "- Show how synthetic labels can leak into features, and avoid it.\n"
    "- Evaluate honestly: cross-validation, a held-out split and rows the model never saw."
)

st.subheader("Data")
st.markdown(
    "- **Source:** the UCI [AI4I 2020 Predictive Maintenance Dataset](https://doi.org/10.24432/C5HS5C) "
    "(Matzka 2020, CC BY 4.0). It is synthetic, and its failure label comes from published rules on its sensors.\n"
    "- **Copied unchanged:** air and process temperature, rotational speed, torque, tool wear and the failure label.\n"
    "- **Generated by this project:** weight, length, width, height, tolerance deviation and the `defective` flag, "
    "made from formulas plus random noise. They are not measurements.\n"
    "- **Training file:** 1,000 sampled rows, with failures oversampled to 15% (3.39% in the source)."
)

st.subheader("Architecture")
st.code(
    "data/raw/ai4i2020.csv ──scripts/adapt_ai4i_dataset.py──▶ manufacturing_samples.csv\n"
    "manufacturing_samples.csv ──src/train.py──▶ models/defect_pipeline.joblib\n"
    "models/defect_pipeline.joblib ──src/report.py──▶ reports/  (figures, tables, metrics.json)\n"
    "models/ + reports/ ──app.py──▶ this Streamlit app  (no training at runtime)",
    language=None,
)

st.subheader("ML pipeline")
st.markdown(
    "1. **Derived features:** temperature difference, power and tool wear × torque, computed from each row's own values.\n"
    "2. **Median imputation** for missing sensor values.\n"
    "3. **Standard scaling.**\n"
    "4. **Random Forest** with 300 trees.\n\n"
    "All steps sit in one scikit-learn `Pipeline`, fitted on the 800-row training split only, so nothing is learned "
    "from test data. A run is flagged as a failure at probability ≥ 0.4, chosen with cross-validation because a "
    "missed failure is assumed to cost more than an inspection."
)

st.subheader("Training and evaluation")
st.markdown(
    "- **Selection:** 5-fold cross-validation repeated 5 times on the training file.\n"
    "- **Held-out check:** a stratified 200-row test split.\n"
    "- **Reporting only:** the 9,000 UCI rows outside the training file. They come from the same synthetic "
    "generator, so they test generalisation to new rows, not to real machines."
)

st.subheader("Limitations")
st.markdown(
    "- **Synthetic data:** scores show how well the model recovers the rules behind a synthetic label. They are "
    "not evidence of real-factory performance.\n"
    "- **Uncalibrated probabilities:** failure probabilities are not calibrated real-world risks.\n"
    "- **Random failures:** random tool-wear and random failures are largely unpredictable by design.\n"
    "- **Rule, not a model:** the part inspection applies a fixed rule to generated fields.\n"
    "- **Not production-ready:** there is no real data, no monitoring and no validation."
)

st.subheader("Technologies")
st.write("Python 3.15, pandas, NumPy, scikit-learn, Matplotlib, joblib, Streamlit and Altair, with `unittest` and GitHub Actions for testing.")

